def show_refugee_analysis():
    st.header("🏕️ تحليل تأثير اللاجئين السوريين")
    st.markdown("**بيانات UNHCR الرسمية - سبتمبر 2025**")
    
    df_refugees = pd.DataFrame(refugee_data_unhcr)
    
    # مؤشرات سريعة
    col1, col2, col3 = st.columns(3)
    
    with col1:
        total_refugees = df_refugees['اللاجئين_السوريين'].sum()
        st.metric("إجمالي اللاجئين السوريين", f"{total_refugees:,}", "UNHCR 2025")
    
    with col2:
        top_gov = df_refugees.loc[df_refugees['اللاجئين_السوريين'].idxmax()]
        st.metric("أعلى محافظة استضافة", top_gov['المحافظة'], f"{top_gov['اللاجئين_السوريين']:,}")
    
    with col3:
        concentration = df_refugees['النسبة_المئوية'].head(3).sum()
        st.metric("التركيز في أعلى 3 محافظات", f"{concentration:.1f}%")
    
    # رسم بياني لتوزيع اللاجئين
    col1, col2 = st.columns(2)
    
    with col1:
        fig1 = px.pie(df_refugees, values='اللاجئين_السوريين', names='المحافظة',
                     title='توزيع اللاجئين السوريين حسب المحافظة')
        st.plotly_chart(fig1, use_container_width=True)
    
    with col2:
        fig2 = px.bar(df_refugees, x='المحافظة', y='اللاجئين_السوريين',
                     color='النسبة_المئوية', title='عدد اللاجئين والنسبة المئوية')
        st.plotly_chart(fig2, use_container_width=True)
    
    # تحليل الارتباط مع المؤشرات التنموية
    st.subheader("📈 تحليل تأثير اللاجئين على المؤشرات التنموية")
    
    df_combined = load_comprehensive_data()
    
    fig3 = px.scatter(df_combined, x='اللاجئين_السوريين', y='معدل_البطالة',
                     size='الكثافة_السكانية', color='المحافظة',
                     hover_name='المحافظة', 
                     title='العلاقة بين أعداد اللاجئين ومعدلات البطالة')
    st.plotly_chart(fig3, use_container_width=True)

def show_governorates_comprehensive():
    st.header("🏛️ التقارير التفصيلية لجميع المحافظات")
    
    df = load_comprehensive_data()
    
    # فلتر المحافظات
    selected_governorates = st.multiselect(
        "اختر المحافظات لعرض تقاريرها التفصيلية:",
        df['المحافظة'].unique(),
        default=['المفرق', 'عمان', 'إربد']
    )
    
    for governorate in selected_governorates:
        if governorate in developmental_challenges_all:
            with st.expander(f"📋 **{governorate} - التقرير التنموي الشامل**", expanded=True):
                show_governorate_detailed_report(governorate)

def show_governorate_detailed_report(governorate):
    """عرض تقرير مفصل لمحافظة معينة"""
    
    df = load_comprehensive_data()
    gov_data = df[df['المحافظة'] == governorate].iloc[0]
    challenges_data = developmental_challenges_all[governorate]
    
    st.write(f"## 🎯 التقرير التنموي لمحافظة {governorate}")
    
    # مؤشرات سريعة
    col1, col2, col3, col4 = st.columns(4)
    
    with col1:
        st.metric("التصنيف التنموي", challenges_data["التصنيف_العام"])
    
    with col2:
        st.metric("معدل البطالة", f"{gov_data['معدل_البطالة']}%")
    
    with col3:
        st.metric("اللاجئين السوريين", f"{gov_data['اللاجئين_السوريين']:,}")
    
    with col4:
        st.metric("مؤشر التنمية البشرية", f"{gov_data['مؤشر_التنمية_البشرية']}")
    
    st.markdown("---")
    
    # التحديات الرئيسية
    st.subheader("🚧 التحديات التنموية الرئيسية")
    
    for i, challenge in enumerate(challenges_data["التحديات_الرئيسية"], 1):
        st.write(f"##### التحدي {i}: {challenge['التحدي']} **(تأثير: {challenge['التأثير']})**")
        
        col1, col2 = st.columns(2)
        
        with col1:
            st.write("**المؤشرات:**")
            for indicator in challenge["المؤشرات"]:
                st.write(f"• {indicator}")
        
        with col2:
            st.write("**الأسباب الجذرية:**")
            for cause in challenge["الأسباب"]:
                st.write(f"• {cause}")
        
        # توصيات قابلة للتنفيذ
        st.write("**🎯 التوصيات التنفيذية:**")
        recommendations = generate_executive_recommendations(governorate, challenge['التحدي'])
        for rec in recommendations:
            st.success(f"• {rec}")
        
        st.markdown("---")

