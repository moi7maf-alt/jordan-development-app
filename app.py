# =================================================================
# App.py - أداة تحليل البيانات التنموية للمحافظات (باستخدام Streamlit)
# =================================================================

import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px

# -----------------------------------------------------------------
# 1. إعدادات الصفحة وتحميل ومعالجة البيانات
# -----------------------------------------------------------------

st.set_page_config(
    page_title="📊 منظومة تحليل التنمية المحلية للمحافظات (2024)",
    layout="wide",
    initial_sidebar_state="expanded"
)

# وظيفة تحميل ومعالجة البيانات الموحدة
@st.cache_data
def load_and_process_data():
    # 1. تحميل ودمج المؤشرات الأساسية (2024/2023)
    
    # 1.1. البطالة والمشاركة الاقتصادية (سنستخدم 2024)
    df_unemployment = pd.read_csv("Data.xlsx - البطالة .csv", header=0)
    df_participation = pd.read_csv("Data.xlsx - المشاركة _الإقتصادية.csv", header=0)
    df_female_participation = pd.read_csv("Statistics of Woman (1).xlsx - Statistics of Woman.csv", header=2)
    df_literacy = pd.read_csv("Data.xlsx - الأمية.csv", header=0)
    
    # تنظيف وتوحيد البطالة
    df_unemployment = df_unemployment[['المحافظة', '2024']].rename(columns={'2024': 'معدل البطالة 2024'}).set_index('المحافظة')

    # تنظيف وتوحيد المشاركة الاقتصادية
    df_participation = df_participation[['المحافظة', '2024']].rename(columns={'2024': 'معدل المشاركة الاقتصادية الكلي 2024'}).set_index('المحافظة')

    # تنظيف وتوحيد الأمية (سنستخدم 2024)
    df_literacy = df_literacy[['المحافظة', '2024']].rename(columns={'2024': 'معدل الأمية الكلي 2024'})
    df_literacy.replace({'عمان': 'العاصمة', 'إربد': 'اربد', 'مادبا': 'مأدبا'}, inplace=True)
    df_literacy = df_literacy.set_index('المحافظة')

    # تنظيف وتوحيد مشاركة الإناث (سنستخدم 2024)
    df_female_participation = df_female_participation.iloc[2:].copy()
    df_female_participation.columns = ['المحافظة', 'المملكة', '2022', '2023', '2024']
    df_female_participation = df_female_participation[['المحافظة', '2024']].rename(columns={'2024': 'معدل مشاركة المرأة في العمل 2024'})
    df_female_participation.replace({'إربد ': 'اربد', 'مأدبا': 'مأدبا', 'إجمالي الإناث': 'المملكة'}, inplace=True)
    df_female_participation = df_female_participation.set_index('المحافظة').dropna()
    df_female_participation['معدل مشاركة المرأة في العمل 2024'] = pd.to_numeric(df_female_participation['معدل مشاركة المرأة في العمل 2024'])
    
    # 1.2. المؤشرات البيئية (سنستخدم 2023)
    df_water = pd.read_csv("Data.xlsx - التزود_المائي.csv", header=0)
    df_water = df_water[['المحافظة', '2023']].rename(columns={'2023': 'حصة الفرد من التزويد المائي 2023 (لتر/يوم)'})
    df_water.replace({'اربد': 'إربد'}, inplace=True)
    df_water = df_water.set_index('المحافظة')
    
    # 1.3. المؤشرات السكانية والمساحة (2024)
    df_density = pd.read_csv("الكثافة السكانية.xlsx - Sheet1.csv", header=3)
    df_density = df_density.iloc[4:17].copy()
    df_density.columns = ['ID', 'المحافظة', 'Col3', 'عدد السكان 2024', 'المساحة (كم2)', 'Col6', 'الكثافة السكانية 2024 (فرد/كم2)', 'English Name']
    df_density = df_density[['المحافظة', 'عدد السكان 2024', 'المساحة (كم2)', 'الكثافة السكانية 2024 (فرد/كم2)']]
    df_density.replace({'اربد': 'إربد', 'مادبا': 'مأدبا'}, inplace=True)
    df_density = df_density.set_index('المحافظة')


    # 2. دمج جميع الجداول في جدول واحد (df)
    df = (
        df_unemployment.join(df_participation, how='outer')
        .join(df_female_participation, how='outer')
        .join(df_literacy, how='outer')
        .join(df_water, how='outer')
        .join(df_density, how='outer')
        .reset_index().rename(columns={'index': 'المحافظة'})
    )
    
    # تنظيف العاصمة واربد في بعض الملفات
    df.replace({'العاصمة': 'عمان'}, inplace=True) 
    df.replace({'اربد': 'إربد'}, inplace=True)
    
    # إزالة الصفوف غير الممثلة للمحافظات (مثل المملكة، إجمالي الإناث)
    df = df[~df['المحافظة'].isin(['المملكة', 'إجمالي الإناث'])].dropna(subset=['المحافظة'])
    
    # توحيد اسم المحافظة ليكون 'المحافظة'
    df['المحافظة'] = df['المحافظة'].apply(lambda x: x.strip())
    
    # تحويل البيانات الرقمية إلى رقمية (مع تجاهل الأخطاء)
    for col in df.columns:
        if col not in ['المحافظة', 'الاتجاه', 'التصنيف']:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    # إضافة المؤشرات القطاعية الأساسية (بافتراض قيم افتراضية وموثقة لاحقاً)
    # لا توجد بيانات للناتج الإقليمي الإجمالي (GRDP) الموثق على مستوى المحافظات في الملفات المرفوعة أو البحث.
    # سنضيف المؤشرات القطاعية الزراعية الموجودة لديك كمؤشرات أولية للفرص.
    
    # مؤشرات الثروة النباتية (محاصيل حقلية 2023) - مؤشر أولي على القدرة الإنتاجية
    df_plant = pd.read_csv("Data.xlsx - ثروة_نباتية.csv", header=1)
    df_plant = df_plant.iloc[4:6].T
    df_plant.columns = ['المحافظة', 'محاصيل حقلية (2020)', 'أشجار مثمرة (2020)']
    df_plant = df_plant.iloc[2:].copy().reset_index(drop=True)
    df_plant['المحافظة'] = df_plant['المحافظة'].ffill().str.strip()
    df_plant = df_plant.iloc[::2].copy().set_index('المحافظة')

    # دمج مؤشرات الثروة النباتية
    df = df.set_index('المحافظة').join(df_plant, how='left').reset_index()
    
    # نحتاج إلى تقدير للناتج الإقليمي (GRDP) وتوزيع قطاعي لتمكين المحور 1.
    # بما أن البيانات غير متوفرة، سنستخدم تقديرات بناءً على الكثافة السكانية والبطالة كمؤشر أولي حتى يتم توفير البيانات الحقيقية.
    df['الناتج الإقليمي المُقدّر (افتراضي)*'] = df['عدد السكان 2024'] * 500  # قيمة افتراضية مقدرة

    # إضافة مؤشر تغطية الصرف الصحي (استناداً لنتائج البحث، المعدل الوطني 68%)
    # لعدم توفر البيانات المفصلة للمحافظات، سنستخدم المؤشر الوطني كمرجع.
    df['نسبة تغطية الصرف الصحي (مؤشر وطني 68%)'] = 68.0 

    return df

df = load_and_process_data()

# -----------------------------------------------------------------
# 2. اللوحة الجانبية للمراجع والتوثيق
# -----------------------------------------------------------------

st.sidebar.header("📚 المراجع والتوثيق المعتمد")
st.sidebar.markdown(
    """
    * **بيانات البطالة، الأمية، والمشاركة الاقتصادية:** دائرة الإحصاءات العامة، **مسح العمالة والبطالة (2024)**.
    * **المؤشرات السكانية والمساحة:** دائرة الإحصاءات العامة، **تقديرات السكان (2024)**.
    * **مؤشرات المياه والبيئة:** وزارة المياه والري، **حصص التزويد المائي (2023)**.
    * **مؤشرات الثروة النباتية:** دائرة الإحصاءات العامة، **الإحصاءات الزراعية (2020)**.
    * **نسبة تغطية الصرف الصحي:** **68%** (وفق تصريح وزير المياه 2023) - **مؤشر وطني يستخدم كمرجع للفجوة التنموية**.
    * **رؤية 2033:** الوثيقة الرسمية **لرؤية التحديث الاقتصادي**.
    """
)
st.sidebar.info("⚠️ ملاحظة: بعض المؤشرات (كالناتج الإقليمي) تم استخدامها كـ **تقدير أولي** لعدم توفر بيانات موثقة على مستوى المحافظات ضمن الملفات المرفوعة.")

# -----------------------------------------------------------------
# 3. مرشحات البيانات (Filters)
# -----------------------------------------------------------------

if not df.empty:
    all_provinces = ['كل المحافظات'] + list(df['المحافظة'].unique())
    selected_province = st.sidebar.selectbox(
        "اختر المحافظة للتحليل التفصيلي:",
        options=all_provinces
    )

    if selected_province != 'كل المحافظات':
        df_filtered = df[df['المحافظة'] == selected_province].iloc[0] # ناخذ الصف الأول (والوحيد) للمحافظة
        st.header(f"🏛️ تقرير التحليل التنموي للمحافظة: **{selected_province}**")
    else:
        df_filtered = df.copy()
        st.header("تقرير التحليل التنموي لـ **كل المحافظات** (نظرة عامة)")
        
    st.markdown("---")
    
    # -----------------------------------------------------------------
    # 4. بناء محاور التحليل الأربعة
    # -----------------------------------------------------------------

    # =================================================================
    # المحور الأول: التحليل القطاعي (التحديات والفرص)
    # =================================================================
    
    st.subheader("1. 📈 المحور القطاعي (تحديات وفرص التنمية الاقتصادية)")
    
    if selected_province != 'كل المحافظات':
        # تحدي: البطالة
        col1, col2, col3 = st.columns(3)
        national_unemployment_avg = df[~df['المحافظة'].str.contains('المملكة', na=False)]['معدل البطالة 2024'].mean()
        
        with col1:
            st.metric(
                label="معدل البطالة (2024)", 
                value=f"{df_filtered['معدل البطالة 2024']:.1f}%",
                delta=f"الفرق عن الوطني: {df_filtered['معدل البطالة 2024'] - national_unemployment_avg:.1f} نقطة"
            )
            st.caption("👈 **تحليل التحدي:** معدل البطالة المرتفع يتطلب مشاريع **إنتاجية وتدريب مهني** موجهة للقطاعات ذات الأولوية في الرؤية.")
            
        # فرصة: الناتج الإقليمي المقدر
        with col2:
            st.metric(
                label="الناتج الإقليمي المُقدّر (افتراضي)*",
                value=f"{df_filtered['الناتج الإقليمي المُقدّر (افتراضي)*'] / 1000000:.2f} مليون دينار"
            )
            st.caption("👈 **تحليل الفرصة:** هذا التقدير يعطي إشارة أولية لحجم الاقتصاد المحلي. يجب توفير بيانات الناتج الإقليمي الإجمالي (GRDP) للتوثيق الكامل.")

        # فرصة: الثروة الزراعية
        with col3:
            st.metric(
                label="مساحة الأراضي المزروعة بالمحاصيل الحقلية (2020)",
                value=f"{df_filtered['محاصيل حقلية (2020)']:.0f} دونم"
            )
            st.caption("👈 **ميزة تنافسية:** التركيز على **الأمن الغذائي والصناعات القائمة على الزراعة** كمحرك تنموي (ضمن محرك الموارد المستدامة - رؤية 2033).")

    else:
        # عرض مقارنة عامة للبطالة بين المحافظات
        df_sorted = df.sort_values(by='معدل البطالة 2024', ascending=False)
        fig_unemployment = px.bar(
            df_sorted, 
            x='المحافظة', 
            y='معدل البطالة 2024', 
            title='مقارنة معدلات البطالة بين المحافظات (2024)',
            color_discrete_sequence=['#FF4B4B'],
            text='معدل البطالة 2024'
        )
        fig_unemployment.update_traces(texttemplate='%{text:.1f}%', textposition='outside')
        st.plotly_chart(fig_unemployment, use_container_width=True)


    st.markdown("---")

    # =================================================================
    # المحور الثاني: التوازن التنموي (الفجوات)
    # =================================================================
    st.subheader("2. ⚖️ محور التوازن التنموي (قياس الفجوات التنموية)")
    st.caption("هذا المحور يقارن أداء المحافظة بمؤشرات وطنية أساسية لبيان **أولوية التدخل التنموي**.")
    
    # 2.1. فجوة الموارد (المياه)
    col4, col5 = st.columns(2)
    national_water_avg = df['حصة الفرد من التزويد المائي 2023 (لتر/يوم)'].mean()
    national_density_avg = df['الكثافة السكانية 2024 (فرد/كم2)'].mean()

    with col4:
        if selected_province != 'كل المحافظات':
            st.metric(
                label="حصة الفرد من التزويد المائي (2023)",
                value=f"{df_filtered['حصة الفرد من التزويد المائي 2023 (لتر/يوم)']:.1f} لتر/يوم",
                delta=f"الفرق عن الوطني: {df_filtered['حصة الفرد من التزويد المائي 2023 (لتر/يوم)'] - national_water_avg:.1f} لتر/يوم"
            )
            st.caption("👈 **التحدي البيئي:** الحصة المنخفضة تشير إلى أولوية مشاريع حصاد المياه وكفاءة الشبكات (مشاريع بنية تحتية).")
        else:
             st.markdown("**مقارنة حصة الفرد من المياه (2023):**")
             fig_water = px.bar(df, x='المحافظة', y='حصة الفرد من التزويد المائي 2023 (لتر/يوم)', title='مقارنة حصة الفرد من التزويد المائي')
             st.plotly_chart(fig_water, use_container_width=True)

    with col5:
        if selected_province != 'كل المحافظات':
            st.metric(
                label="الكثافة السكانية (2024)",
                value=f"{df_filtered['الكثافة السكانية 2024 (فرد/كم2)']:.0f} فرد/كم²",
                delta=f"الفرق عن الوطني: {df_filtered['الكثافة السكانية 2024 (فرد/كم2)'] - national_density_avg:.0f} فرد/كم²"
            )
            st.caption("👈 **التحدي الإداري:** الكثافة العالية (فوق الوطني) تتطلب توجيه استثمارات نحو البنية التحتية والخدمات العامة، والكثافة المنخفضة تتطلب تحفيز التوطين الاقتصادي.")
        else:
            st.markdown("**مقارنة الكثافة السكانية (2024):**")
            fig_density = px.bar(df, x='المحافظة', y='الكثافة السكانية 2024 (فرد/كم2)', title='مقارنة الكثافة السكانية')
            st.plotly_chart(fig_density, use_container_width=True)
            
    # 2.2. فجوة التعليم (الأمية)
    if selected_province != 'كل المحافظات':
        national_literacy_avg = df['معدل الأمية الكلي 2024'].mean()
        st.metric(
            label="معدل الأمية الكلي (2024)", 
            value=f"{df_filtered['معدل الأمية الكلي 2024']:.2f}%",
            delta=f"الفرق عن الوطني: {df_filtered['معدل الأمية الكلي 2024'] - national_literacy_avg:.2f} نقطة"
        )
        st.caption("👈 **التحدي التعليمي:** معدل الأمية الأعلى من الوطني يشير إلى حاجة ماسة لبرامج محو أمية وتعليم الكبار، وهو شرط أساسي لنجاح التنمية الاقتصادية في المحافظة.")
        
    st.markdown("---")
    
    # =================================================================
    # المحور الثالث: الموائمة مع رؤية 2033 (مقترح)
    # =================================================================
    st.subheader("3. ⭐ موائمة المشاريع مع رؤية التحديث الاقتصادي 2033")
    
    st.markdown("""
    لتحقيق الموائمة، يجب ربط المشاريع المقترحة للمحافظة بأحد **محركات رؤية 2033** الثمانية (مثل: الاستثمار، الصناعة عالية القيمة، الريادة، الطاقة، إلخ).
    """)
    
    # مثال توضيحي للموائمة (يجب تزويد هذا الجدول ببيانات مشاريعك المقترحة فعلياً)
    st.table(
        pd.DataFrame({
            'المشروع المقترح للمحافظة': [
                "إنشاء مركز تدريب مهني تخصصي في صيانة المعدات الزراعية", 
                "تطوير مسار بيئي سياحي في المنطقة الجنوبية للمحافظة"
            ],
            'محرك رؤية 2033 المستهدف': [
                "الريادة والإبداع، الموارد المستدامة",
                "الأردن وجهة عالمية"
            ],
            'مؤشر النجاح المحلي (KPI)': [
                "تدريب 500 شاب، توفير 100 فرصة عمل مباشرة",
                "زيادة الليالي المبيتة بنسبة 15% سنوياً"
            ]
        })
    )
    st.caption("👈 **توجيه القرار:** استخدام هذه الآلية يضمن أن خطة المحافظة تخدم الأهداف الوطنية وتزيد من فرص التمويل المركزي والدولي.")
    
    st.markdown("---")
    
    # =================================================================
    # المحور الرابع: تنمية المرأة (التمكين الاقتصادي)
    # =================================================================
    st.subheader("4. 🚺 محور تنمية المرأة والتمكين الاقتصادي")
    
    if selected_province != 'كل المحافظات':
        
        # 4.1. معدل مشاركة المرأة في العمل
        national_female_participation_avg = df[~df['المحافظة'].str.contains('المملكة', na=False)]['معدل مشاركة المرأة في العمل 2024'].mean()
        
        st.metric(
            label="معدل مشاركة المرأة في القوى العاملة (2024)", 
            value=f"{df_filtered['معدل مشاركة المرأة في العمل 2024']:.1f}%",
            delta=f"الفرق عن الوطني: {df_filtered['معدل مشاركة المرأة في العمل 2024'] - national_female_participation_avg:.1f} نقطة"
        )
        st.caption("👈 **مؤشر التمكين:** يشير **الانخفاض** عن المستوى الوطني (أو عن المحافظات الأخرى) إلى ضرورة تخصيص مشاريع لدعم ريادة الأعمال النسوية وتوفير بيئة عمل داعمة لزيادة المعدل. على سبيل المثال، محافظة **الكرك** (22.4%) و **الطفيلة** (19.0%) لديها أعلى معدلات مشاركة للإناث، ما يجعلهما نماذج عمل لمشاريع التمكين.")

    else:
        # رسم بياني لمقارنة مشاركة المرأة بين المحافظات
        df_sorted_female = df.sort_values(by='معدل مشاركة المرأة في العمل 2024', ascending=False)
        fig_female = px.bar(
            df_sorted_female, 
            x='المحافظة', 
            y='معدل مشاركة المرأة في العمل 2024', 
            title='مقارنة معدلات مشاركة المرأة في القوى العاملة (2024)',
            color_discrete_sequence=['#FFC0CB'],
            text='معدل مشاركة المرأة في العمل 2024'
        )
        fig_female.update_traces(texttemplate='%{text:.1f}%', textposition='outside')
        st.plotly_chart(fig_female, use_container_width=True)


# -----------------------------------------------------------------
# 5. تنبيه إذا كانت البيانات فارغة
# -----------------------------------------------------------------
else:
    st.error("حدث خطأ في تحميل أو معالجة البيانات. يرجى مراجعة أسماء الأعمدة في ملفات CSV.")
