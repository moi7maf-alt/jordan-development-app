df = pd.DataFrame(data)
df.set_index('المحافظة', inplace=True)

# 2. تحديد اتجاهات المؤشرات (1=إيجابي/الأعلى أفضل، -1=سلبي/الأقل أفضل)
indicator_direction = {
    'معدل البطالة الإجمالي (2024) (%)': -1,
    'متوسط إجمالي الدخل السنوي (JD)': 1,
    'فجوة المشاركة الاقتصادية (2024) (%)': -1,
    'معدل المشاركة الاقتصادية للإناث (2024) (%)': 1,
    'نسبة الأمية (2024) (%)': -1,
    'عدد الأسرة لكل 1000 نسمة (2024)': 1,
    'حصة الفرد من التزويد المائي لتر/يوم (2023)': 1,
    'الكثافة السكانية (2024) (فرد/كم²)': -1
}

# 3. دالة التطبيع (Normalization)
def normalize_data(series, direction):
    """تحويل القيم إلى درجة موحدة من 0 إلى 100 بناءً على الاتجاه."""
    min_val = series.min()
    max_val = series.max()
    
    if max_val == min_val:
        return pd.Series([100.0] * len(series), index=series.index)

    if direction == 1: # مؤشر إيجابي (الأعلى أفضل)
        return ((series - min_val) / (max_val - min_val)) * 100
    else: # مؤشر سلبي (الأقل أفضل)
        return ((max_val - series) / (max_val - min_val)) * 100

# 4. تطبيق التطبيع وحساب الدرجات
df_scores = pd.DataFrame(index=df.index)
for col, direction in indicator_direction.items():
    new_col_name = f'درجة {col}'
    df_scores[new_col_name] = normalize_data(df[col], direction).round(1)

# 5. حساب المؤشرات المركبة الرئيسية

# 5.1. مؤشر التنمية المركب العام (متوسط متساوي)
df_scores['المؤشر التنموي المركب العام (من 100)'] = df_scores.mean(axis=1).round(1)

# 5.2. مؤشر تنمية المرأة المركب (المشاركة + فجوة المشاركة)
women_cols = ['درجة معدل المشاركة الاقتصادية للإناث (2024) (%)', 'درجة فجوة المشاركة الاقتصادية (2024) (%)']
df_scores['مؤشر تنمية المرأة المركب (من 100)'] = df_scores[women_cols].mean(axis=1).round(1)

# 6. إضافة الترتيبات النهائية
df_scores['الترتيب العام'] = df_scores['المؤشر التنموي المركب العام (من 100)'].rank(ascending=False).astype(int)
df_scores['ترتيب تنمية المرأة'] = df_scores['مؤشر تنمية المرأة المركب (من 100)'].rank(ascending=False).astype(int)

# 7. دمج البيانات الأصلية مع الدرجات والترتيب
final_analysis_df = pd.concat([df, df_scores], axis=1)

# 8. طباعة المخرجات النهائية (ملف CSV جاهز)
print("="*60)
